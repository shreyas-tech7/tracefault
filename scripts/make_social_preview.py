def canvas():
    return [[BG] * W for _ in range(H)]


def rect(px, x0, y0, x1, y1, color):
    for y in range(max(0, y0), min(H, y1)):
        row = px[y]
        for x in range(max(0, x0), min(W, x1)):
            row[x] = color


def text(px, s, x, y, scale, color):
    for ch in s.upper():
        glyph = FONT[ch]
        for gy, line in enumerate(glyph):
            for gx, bit in enumerate(line):
                if bit == "1":
                    rect(
                        px,
                        x + gx * scale,
                        y + gy * scale,
                        x + (gx + 1) * scale,
                        y + (gy + 1) * scale,
                        color,
                    )
        x += 6 * scale
    return x


def png(px) -> bytes:
    raw = b"".join(b"\x00" + bytes(c for p in row for c in p) for row in px)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))

    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def main() -> None:
    px = canvas()
    rect(px, 0, 0, W, 12, ACCENT)
    text(px, "tracefault", 80, 110, 14, FG)
    text(px, "find the agent runs that went wrong", 84, 260, 5, ACCENT)
    text(px, "loops, tool errors, overflow, timeouts", 84, 330, 5, MUTED)
    text(px, "and blown budgets in your traces", 84, 390, 5, MUTED)
    # A decorative waterfall of five spans. The shapes are fixed, not results.
    for i, (x0, x1) in enumerate([(700, 1180), (720, 840), (850, 980), (990, 1100), (1110, 1170)]):
        color = BARS[i % 3] if i else ACCENT
        rect(px, x0, 462 + i * 22, x1, 478 + i * 22, color)
    rect(px, 80, 590, 1200, 594, MUTED)
    out = Path(__file__).resolve().parents[1] / "docs" / "social-preview.png"
    out.write_bytes(png(px))
    print("wrote", out, W, "x", H)


if __name__ == "__main__":
    main()
